// ── Core state ────────────────────────────────────────────────────────────────

var currentLang = localStorage.getItem('bp_lang') || 'en';

// ── Translation lookup ────────────────────────────────────────────────────────

function t(key) {
    return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
        || (TRANSLATIONS.en && TRANSLATIONS.en[key])
        || key;
}

// ── Apply all data-i18n attributes in the DOM ─────────────────────────────────

function applyTranslations() {
    // data-i18n → textContent
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // data-i18n-placeholder → placeholder attribute
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        var key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key);
    });

    // data-i18n-title → title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        var key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });

    // Update html lang attribute
    document.documentElement.lang = currentLang === 'rw' ? 'rw' : 'en';

    // Update all lang-btn elements: show the language you will switch TO
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
        btn.textContent = currentLang === 'rw' ? 'EN' : 'RW';
    });
}

// ── Language setters ──────────────────────────────────────────────────────────

function setLang(lang) {
    currentLang = lang;
    localStorage.setItem('bp_lang', lang);
    applyTranslations();
}

function toggleLang() {
    setLang(currentLang === 'rw' ? 'en' : 'rw');
}

// ── Boot ──────────────────────────────────────────────────────────────────────

document.addEventListener('DOMContentLoaded', function () {
    applyTranslations();
});
